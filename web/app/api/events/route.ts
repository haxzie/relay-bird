import { POSTHOG_HOST, POSTHOG_TOKEN } from '@/lib/analytics'

export const dynamic = 'force-dynamic'

/**
 * The relay the desktop app reports to.
 *
 * The app posts here rather than to PostHog directly for two reasons: the endpoint is ours,
 * so where the data goes can change without shipping a new build; and the server decides
 * what is acceptable rather than trusting whatever a client sends.
 *
 * What is deliberately not accepted: anything resembling message content, phone numbers or
 * contact names. The allow-lists below are the entire vocabulary. A product whose whole
 * claim is that messages stay on your network must not have a telemetry endpoint capable of
 * carrying one.
 */
const ALLOWED_EVENTS = new Set([
  'app_launched',
  'phone_paired',
  'phone_connected',
  'phone_forgotten',
  'messages_opened',
  'thread_opened',
  'notification_clicked',
  'update_installed',
])

/** Scalars only, and only these keys. Anything else is dropped rather than forwarded. */
const ALLOWED_PROPERTIES = new Set([
  'app_version',
  'os_version',
  'platform',
  'device_model',
  'thread_count',
  'reconnect',
])

type Payload = { event?: unknown; distinctId?: unknown; properties?: unknown }

function clean(properties: unknown): Record<string, string | number | boolean> {
  if (typeof properties !== 'object' || properties === null) return {}
  const out: Record<string, string | number | boolean> = {}
  for (const [key, value] of Object.entries(properties)) {
    if (!ALLOWED_PROPERTIES.has(key)) continue
    if (typeof value === 'string') out[key] = value.slice(0, 64)
    else if (typeof value === 'number' || typeof value === 'boolean') out[key] = value
  }
  return out
}

export async function POST(request: Request) {
  if (!POSTHOG_TOKEN) return new Response(null, { status: 204 })

  let body: Payload
  try {
    body = (await request.json()) as Payload
  } catch {
    return Response.json({ error: 'expected JSON' }, { status: 400 })
  }

  const event = typeof body.event === 'string' ? body.event : ''
  if (!ALLOWED_EVENTS.has(event)) {
    return Response.json({ error: 'unknown event' }, { status: 400 })
  }

  // A random install id generated by the app. Rejecting anything that is not a plain UUID
  // stops this becoming a channel for carrying something identifying.
  const distinctId = typeof body.distinctId === 'string' ? body.distinctId : ''
  if (!/^[0-9a-fA-F-]{36}$/.test(distinctId)) {
    return Response.json({ error: 'bad distinctId' }, { status: 400 })
  }

  try {
    await fetch(`${POSTHOG_HOST}/i/v0/e/`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        api_key: POSTHOG_TOKEN,
        event,
        distinct_id: distinctId,
        properties: { ...clean(body.properties), source: 'desktop' },
        timestamp: new Date().toISOString(),
      }),
    })
  } catch {
    // The app must never care whether this worked.
  }

  return new Response(null, { status: 204 })
}
